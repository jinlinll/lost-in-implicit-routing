# ─── ANSI Colors ──────────────────────────────────────────────────────

def _supports_color() -> bool:
    if os.environ.get("NO_COLOR"):
        return False
    if os.environ.get("FORCE_COLOR"):
        return True
    return hasattr(sys.stdout, "isatty") and sys.stdout.isatty()

USE_COLOR = _supports_color()

def _c(code: str, text: str) -> str:
    if not USE_COLOR:
        return text
    return f"\033[{code}m{text}\033[0m"

def green(t: str) -> str: return _c("32", t)
def red(t: str) -> str: return _c("31", t)
def yellow(t: str) -> str: return _c("33", t)
def cyan(t: str) -> str: return _c("36", t)
def bold(t: str) -> str: return _c("1", t)
def dim(t: str) -> str: return _c("2", t)
def magenta(t: str) -> str: return _c("35", t)


def _rate_color(rate: float) -> str:
    """Color a rate string based on value."""
    text = f"{rate:5.1f}%"
    if rate >= 80:
        return green(text)
    elif rate >= 40:
        return yellow(text)
    elif rate > 0:
        return red(text)
    else:
        return dim(text)


# ─── Golden Skills Discovery ─────────────────────────────────────────

def discover_golden_skills(tasks_dir: Path) -> Dict[str, Set[str]]:
    """
    Discover golden skills for each task.
    
    Golden skills are defined under:
      tasks_dir/{task_name}/environment/skills/{skill_folder}/SKILL.md
    
    The skill name is taken from the 'name:' field in SKILL.md (not the folder name),
    because the agent loads skills by SKILL.md name, which may differ from folder name.
    
    Returns: {task_name: {skill_name_1, skill_name_2, ...}}
    """
    import re as _re
    golden = {}
    if not tasks_dir.exists():
        return golden
    
    for task_dir in sorted(tasks_dir.iterdir()):
        if not task_dir.is_dir():
            continue
        skills_dir = task_dir / "environment" / "skills"
        if not skills_dir.exists():
            continue
        skill_names = set()
        for d in skills_dir.iterdir():
            if not d.is_dir():
                continue
            skill_md = d / "SKILL.md"
            if not skill_md.exists():
                continue
            content = skill_md.read_text()
            m = _re.search(r'^name:\s*(.+)', content, _re.MULTILINE)
            if m:
                name = m.group(1).strip().strip('"').strip("'")
                skill_names.add(name)
            else:
                skill_names.add(d.name)  # fallback to folder name
        if skill_names:
            golden[task_dir.name] = skill_names
    
    return golden


# ─── Result Loading ──────────────────────────────────────────────────

def load_results(logs_dir: Path) -> List[dict]:
    """Load all result.json files, tagging each with preselect_strategy.

    Also attempts to load ``skills_loaded.json`` (generated by
    ``parse_skills_loaded.py``) from the same directory as each
    ``result.json``.  If that file exists the merged skill list is stored
    under the ``_skills_loaded_override`` key so that
    ``get_unique_loaded_skills`` can prefer it over the potentially
    incomplete ``agent_result.loaded_skills``.

    When ``skills_loaded.json`` does not exist **and** the
    ``parse_skills_loaded`` module is importable, we fall back to
    on-the-fly parsing of episode logs in the same directory.
    """
    # Infer strategy from directory name
    dir_name = logs_dir.name
    if dir_name.startswith("experiment_logs-"):
        dir_strategy = dir_name.split("experiment_logs-", 1)[1]
    elif dir_name == "experiment_logs":
        dir_strategy = "naive"
    else:
        dir_strategy = "naive"
    
    results = []
    for result_file in sorted(logs_dir.rglob("result.json")):
        if "_image_cache" in str(result_file):
            continue
        try:
            data = json.loads(result_file.read_text())
            data["_path"] = str(result_file)
            if "preselect_strategy" not in data:
                data["preselect_strategy"] = dir_strategy

            # ── Load merged skills (cat + JSON) ──
            pass_dir = result_file.parent
            skills_loaded_file = pass_dir / "skills_loaded.json"
            if skills_loaded_file.exists():
                try:
                    sl = json.loads(skills_loaded_file.read_text())
                    data["_skills_loaded_override"] = sl.get("skill_names", [])
                except (json.JSONDecodeError, OSError):
                    pass
            elif _parse_pass_dir is not None:
                # On-the-fly fallback: parse episode logs directly
                try:
                    parsed = _parse_pass_dir(pass_dir)
                    if parsed:
                        data["_skills_loaded_override"] = parsed.get("skill_names", [])
                except Exception:
                    pass

            results.append(data)
        except (json.JSONDecodeError, OSError) as e:
            print(f"⚠ Skipping {result_file}: {e}", file=sys.stderr)
    return results


def discover_log_dirs(base_dir: Path) -> List[tuple]:
    """Auto-discover experiment log directories for all strategies."""
    found = []
    main_dir = base_dir / "experiment_logs"
    if main_dir.exists():
        found.append(("naive", main_dir))
    for d in sorted(base_dir.iterdir()):
        if d.is_dir() and d.name.startswith("experiment_logs-"):
            strategy = d.name.split("experiment_logs-", 1)[1]
            found.append((strategy, d))
    return found


def filter_results(
    results: List[dict],
    models: Optional[List[str]] = None,
    tasks: Optional[List[str]] = None,
    skills: Optional[List[int]] = None,
    strategies: Optional[List[str]] = None,
) -> List[dict]:
    filtered = results
    if models:
        filtered = [r for r in filtered if r.get("model_name") in models]
    if tasks:
        filtered = [r for r in filtered if r.get("task_name") in tasks]
    if skills is not None:
        filtered = [r for r in filtered if r.get("extra_skills_count") in skills]
    if strategies:
        filtered = [r for r in filtered if r.get("preselect_strategy") in strategies]
    return filtered


# ─── Hit Rate Calculation ─────────────────────────────────────────────

def get_unique_loaded_skills(result: dict) -> Set[str]:
    """Extract unique skill names loaded in a single pass.

    Prefers the merged ``_skills_loaded_override`` (from
    ``skills_loaded.json`` or on-the-fly episode parsing) which captures
    both ``cat``-loaded and ``load_skill`` JSON-loaded skills.  Falls back
    to the original ``agent_result.loaded_skills`` when the override is
    not available.
    """
    # Prefer merged data (cat + JSON)
    override = result.get("_skills_loaded_override")
    if override is not None:
        return set(override)

    # Fallback: original result.json data (JSON load_skill only)
    loaded_skills = result.get("agent_result", {}).get("loaded_skills", [])
    if not loaded_skills:
        return set()
    return {entry["skill"] for entry in loaded_skills if isinstance(entry, dict) and "skill" in entry}


def calc_hit_rate(loaded: Set[str], golden: Set[str]) -> Tuple[float, int, int, Set[str], Set[str]]:
    """
    Calculate hit rate for a single pass.
    
    Returns: (hit_rate, n_hits, n_golden, hits, non_golden_loaded)
    """
    if not golden:
        return (0.0, 0, 0, set(), loaded)
    hits = loaded & golden
    non_golden = loaded - golden
    rate = len(hits) / len(golden) * 100.0
    return (rate, len(hits), len(golden), hits, non_golden)


def calc_avg_hit_rate_for_group(
    group_results: List[dict], golden: Set[str]
) -> Tuple[float, float, float, int]:
    """
    Calculate average hit rate across passes for a (task, model, skills_count) group.
    
    Returns: (avg_hit_rate, avg_precision, avg_n_loaded, n_valid_passes)
    """
    rates = []
    precisions = []
    n_loaded_list = []
    
    for r in group_results:
        loaded = get_unique_loaded_skills(r)
        if golden:
            hits = loaded & golden
            rate = len(hits) / len(golden) * 100.0
        else:
            rate = 0.0
            hits = set()
        rates.append(rate)
        
        # Precision: of what was loaded, how many are golden?
        if loaded:
            precision = len(hits) / len(loaded) * 100.0
        else:
            precision = 100.0  # Loaded nothing → no false positives
        precisions.append(precision)
        n_loaded_list.append(len(loaded))
    
    n_passes = len(rates)
    avg_rate = sum(rates) / n_passes if n_passes > 0 else 0.0
    avg_precision = sum(precisions) / n_passes if n_passes > 0 else 0.0
    avg_n_loaded = sum(n_loaded_list) / n_passes if n_passes > 0 else 0.0
    
    return avg_rate, avg_precision, avg_n_loaded, n_passes


