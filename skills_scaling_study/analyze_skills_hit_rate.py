#!/usr/bin/env python3
"""
Skills Hit Rate Analyzer
========================
Analyzes how well models identify and load the correct ("golden") skills
from the available skill pool.

Golden skills = skills bundled with each task under environment/skills/.
Hit rate = |loaded ∩ golden| / |golden|  (per unique skill, 3 passes averaged)

Supports multiple log directories for comparing pre-selection strategies:
  experiment_logs/      → naive (default, all skills in prompt)
  experiment_logs-llm/  → LLM pre-selection
  experiment_logs-rag/  → RAG pre-selection

Usage:
    python analyze_skills_hit_rate.py                        # Full report
    python analyze_skills_hit_rate.py --model claude-opus-4-6  # Filter by model
    python analyze_skills_hit_rate.py --task 3d-scan-calc      # Filter by task
    python analyze_skills_hit_rate.py --skills 0 10            # Filter by skills count
    python analyze_skills_hit_rate.py --csv hit_rate.csv       # Export to CSV
    python analyze_skills_hit_rate.py --detail                 # Show per-pass detail

    # Multi-strategy analysis:
    python analyze_skills_hit_rate.py --all-strategies         # Auto-discover all strategies
    python analyze_skills_hit_rate.py --logs-dir experiment_logs experiment_logs-llm
    python analyze_skills_hit_rate.py --strategy llm           # Filter by strategy
"""

