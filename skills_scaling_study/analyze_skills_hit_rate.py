def print_per_task_detail(
    results: List[dict],
    golden_skills: Dict[str, Set[str]],
):
    """Per-task detail showing hit rate, precision, and which skills were loaded."""
    tasks = sorted(set(r["task_name"] for r in results))
    models = sorted(set(r["model_name"] for r in results))
    skills_counts = sorted(set(r["extra_skills_count"] for r in results))
    
    lookup: Dict[Tuple[str, str, int], List[dict]] = defaultdict(list)
    for r in results:
        lookup[(r["task_name"], r["model_name"], r["extra_skills_count"])].append(r)
    
    print(bold("┌─ 📋 Per-Task Skills Hit Detail ──────────────────────────────────┐"))
    print()
    
    for task in tasks:
        golden = golden_skills.get(task, set())
        
        if not golden:
            print(f"  📋 {bold(task)}  {dim('(no golden skills)')}")
            # Still show what was loaded
            task_results = [r for r in results if r["task_name"] == task]
            all_loaded = set()
            for r in task_results:
                all_loaded |= get_unique_loaded_skills(r)
            if all_loaded:
                print(f"     Loaded: {', '.join(sorted(all_loaded))}")
            print()
            continue
        
        print(f"  📋 {bold(task)}  golden={green(str(len(golden)))} {{{', '.join(magenta(s) for s in sorted(golden))}}}")
        
        for model in models:
            parts = []
            for sc in skills_counts:
                group = lookup[(task, model, sc)]
                if not group:
                    continue
                avg_rate, avg_prec, avg_loaded, n = calc_avg_hit_rate_for_group(group, golden)
                
                # Collect all unique loaded skills across passes
                all_loaded = set()
                for r in group:
                    all_loaded |= get_unique_loaded_skills(r)
                
                hits = all_loaded & golden
                misses = golden - all_loaded
                extras = all_loaded - golden
                
                hit_str = _rate_color(avg_rate)
                parts.append(f"s{sc}={hit_str}")
            
            if parts:
                # Overall for this model+task
                all_model_task = [r for r in results if r["task_name"] == task and r["model_name"] == model]
                all_loaded = set()
                for r in all_model_task:
                    all_loaded |= get_unique_loaded_skills(r)
                
                hits = all_loaded & golden
                extras = all_loaded - golden
                
                hits_str = ', '.join(green(s) for s in sorted(hits)) if hits else dim("none")
                extras_str = ', '.join(red(s) for s in sorted(extras)) if extras else ""
                skill_info = f"  ✓{hits_str}"
                if extras_str:
                    skill_info += f"  ✗{extras_str}"
                
                print(f"     {cyan(model):<32s}  {' | '.join(parts)}{skill_info}")
        print()


def print_pass_detail(
    results: List[dict],
    golden_skills: Dict[str, Set[str]],
):
    """Show per-pass detail for each task × model × skills_count."""
    tasks = sorted(set(r["task_name"] for r in results))
    models = sorted(set(r["model_name"] for r in results))
    skills_counts = sorted(set(r["extra_skills_count"] for r in results))
    
    lookup: Dict[Tuple[str, str, int], List[dict]] = defaultdict(list)
    for r in results:
        lookup[(r["task_name"], r["model_name"], r["extra_skills_count"])].append(r)
    
    print(bold("┌─ 🔍 Per-Pass Detail ─────────────────────────────────────────────┐"))
    print()
    
    for task in tasks:
        golden = golden_skills.get(task, set())
        if not golden:
            continue
        
        print(f"  📋 {bold(task)}  golden={{{', '.join(sorted(golden))}}}")
        
        for model in models:
            for sc in skills_counts:
                group = lookup[(task, model, sc)]
                if not group:
                    continue
                
                for r in sorted(group, key=lambda x: x.get("pass_index", 0)):
                    pi = r.get("pass_index", "?")
                    loaded = get_unique_loaded_skills(r)
                    hits = loaded & golden
                    extras = loaded - golden
                    rate = len(hits) / len(golden) * 100.0 if golden else 0.0
                    
                    loaded_str = ", ".join(
                        green(s) if s in golden else red(s) for s in sorted(loaded)
                    ) if loaded else dim("none")
                    
                    print(f"     {cyan(model):<20s} s={sc:<5d} p={pi}  "
                          f"hit={_rate_color(rate)}  "
                          f"loaded=[{loaded_str}]")
        print()


def print_non_golden_frequency(
    results: List[dict],
    golden_skills: Dict[str, Set[str]],
):
    """Show which non-golden skills are most frequently loaded."""
    non_golden_counts: Dict[str, int] = defaultdict(int)
    golden_counts: Dict[str, int] = defaultdict(int)
    
    for r in results:
        task = r.get("task_name", "")
        golden = golden_skills.get(task, set())
        loaded = get_unique_loaded_skills(r)
        
        for s in loaded:
            if s in golden:
                golden_counts[s] += 1
            else:
                non_golden_counts[s] += 1
    
    if non_golden_counts:
        print(bold("┌─ ⚠️  Most Frequently Loaded Non-Golden Skills ───────────────────┐"))
        print()
        for skill, count in sorted(non_golden_counts.items(), key=lambda x: -x[1])[:20]:
            bar = red("█" * min(count, 40))
            print(f"  {count:>4d}  {bar}  {skill}")
        print()


